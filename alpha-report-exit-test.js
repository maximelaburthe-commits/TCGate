'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createSessionGate } = require('./public/alpha-report-exit.js');
let assertions = 0;
function equal(actual, expected, message) { assert.equal(actual, expected, message); assertions++; }
const gate = createSessionGate();
equal(gate.shouldRemind(null), false, 'No reminder without a joined session');
gate.observe('ROOMA1');
equal(gate.shouldRemind('ROOMA1'), true, 'A fresh session offers the optional report');
gate.observe('ROOMA1');
equal(gate.shouldRemind('ROOMA1'), true, 'Screen refresh within the session does not fabricate a sent report');
gate.markSent('OTHER1');
equal(gate.shouldRemind('ROOMA1'), true, 'A late response for another session does not suppress the reminder');
gate.markSent('ROOMA1');
equal(gate.shouldRemind('ROOMA1'), false, 'A confirmed report suppresses subsequent reminders in this session');
gate.observe('ROOMA1');
equal(gate.shouldRemind('ROOMA1'), false, 'Lobby to game preserves a successful report');
gate.observe(null);
equal(gate.shouldRemind('ROOMA1'), false, 'Leaving clears the active session');
gate.observe('ROOMA1');
equal(gate.shouldRemind('ROOMA1'), true, 'Rejoining starts a new reporting session even with the same room code');
gate.observe('ROOMB2');
gate.markSent('ROOMA1');
equal(gate.shouldRemind('ROOMB2'), true, 'Stale success from a former room cannot affect a new room');
gate.markSent(null);
equal(gate.shouldRemind('ROOMB2'), true, 'Missing success context is never accepted');
const source = fs.readFileSync('public/alpha-report-exit.js', 'utf8');
equal(/beforeunload|pagehide|unload|visibilitychange|\.fetch\(|fetch\(/.test(source), false, 'Reminder neither intercepts browser closure nor creates a second delivery system');
console.log('ALPHA_REPORT_EXIT_OK ' + assertions + ' assertions');